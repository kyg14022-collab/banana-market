create or replace function public.is_admin()
returns boolean
language sql
stable
as $$
  select coalesce(auth.jwt() ->> 'email', '') = 'ADMIN_EMAIL@example.com'
$$;
-- 위 'ADMIN_EMAIL@example.com' 을 관리자 이메일로 바꾸세요. (작은따옴표는 남겨 두세요)

-- 2) 표(테이블) 만들기 ------------------------------------------------
create table if not exists public.complexes (
  id            bigint generated by default as identity primary key,
  name          text    not null unique,
  dong          text    not null check (dong in ('반포동', '잠원동')),
  households    integer check (households > 0),
  approval_date date,
  address       text,
  created_at    timestamptz not null default now()
);

create table if not exists public.listings (
  id             bigint generated by default as identity primary key,
  complex_id     bigint  not null references public.complexes (id) on update cascade on delete restrict,
  address        text,
  deal           text    not null default '매매' check (deal = '매매'),
  price          numeric not null check (price >= 0),       -- 매매 금액 (억 단위)
  exclusive_area numeric not null,
  supply_area    numeric not null,
  py_cat         text    not null check (py_cat in ('p0', 'p2', 'p3', 'p4')),
  py_text        text    not null,
  floor_no       integer not null,
  total_floors   integer not null,
  move_in        text    not null,
  rooms          integer not null,
  baths          integer not null,
  approval_date  date    not null,
  parking        text    not null,
  mgmt_fee       integer not null,
  direction      text    not null,
  gap            text check (gap in ('갭투', '입주')),
  tagline        text,
  description    text,
  recommended    boolean not null default false,
  created_at     timestamptz not null default now(),
  check (floor_no <= total_floors)
);

